-- =====================================================================
-- Q&A System database schema
-- Runs on every start; IF NOT EXISTS makes that safe.
-- Written to work in both H2 (PostgreSQL mode) and real PostgreSQL.
-- =====================================================================

-- ---------- Users and their roles ----------
CREATE TABLE IF NOT EXISTS users (
    username       VARCHAR(30)  PRIMARY KEY,
    password_hash  VARCHAR(200) NOT NULL          -- never the real password
);

CREATE TABLE IF NOT EXISTS user_roles (
    username  VARCHAR(30) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    role      VARCHAR(20) NOT NULL,
    PRIMARY KEY (username, role)                   -- a user has each role at most once
);

-- ---------- Invitations ----------
CREATE TABLE IF NOT EXISTS invitations (
    code        VARCHAR(20) PRIMARY KEY,
    expires_at  TIMESTAMP   NOT NULL,
    used        BOOLEAN     NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS invitation_roles (
    code  VARCHAR(20) NOT NULL REFERENCES invitations(code) ON DELETE CASCADE,
    role  VARCHAR(20) NOT NULL,
    PRIMARY KEY (code, role)
);

-- ---------- Courses and chapters ----------
CREATE TABLE IF NOT EXISTS courses (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- keeps the order courses were added
    code   VARCHAR(15)  NOT NULL UNIQUE,                         -- e.g. 'MAT 117'
    title  VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS chapters (
    course_code  VARCHAR(15)  NOT NULL REFERENCES courses(code) ON DELETE CASCADE,
    number       INT          NOT NULL,
    title        VARCHAR(200) NOT NULL,
    PRIMARY KEY (course_code, number)              -- chapter numbers are unique per course
);

-- Which courses each user follows
CREATE TABLE IF NOT EXISTS follows (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,  -- keeps follow order
    username     VARCHAR(30) NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    course_code  VARCHAR(15) NOT NULL REFERENCES courses(code) ON DELETE CASCADE,
    UNIQUE (username, course_code)
);

-- ---------- Questions, answers, reviews ----------
CREATE TABLE IF NOT EXISTS questions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code         VARCHAR(15)   NOT NULL,
    chapter_number      INT           NOT NULL,
    title               VARCHAR(150)  NOT NULL,
    body                VARCHAR(5000) NOT NULL,
    author              VARCHAR(30)   NOT NULL REFERENCES users(username),
    created_at          TIMESTAMP     NOT NULL,
    accepted_answer_id  BIGINT,                    -- NULL = unresolved
    -- Deleting a chapter (or its course) deletes its questions:
    FOREIGN KEY (course_code, chapter_number)
        REFERENCES chapters(course_code, number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS answers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  BIGINT        NOT NULL REFERENCES questions(id) ON DELETE CASCADE,
    text         VARCHAR(5000) NOT NULL,
    author       VARCHAR(30)   NOT NULL REFERENCES users(username),
    created_at   TIMESTAMP     NOT NULL
);

CREATE TABLE IF NOT EXISTS reviews (
    answer_id   BIGINT        NOT NULL REFERENCES answers(id) ON DELETE CASCADE,
    reviewer    VARCHAR(30)   NOT NULL REFERENCES users(username),
    verdict     VARCHAR(20)   NOT NULL,
    comment     VARCHAR(2000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL,
    updated_at  TIMESTAMP     NOT NULL,
    PRIMARY KEY (answer_id, reviewer)              -- one review per reviewer per answer
);
